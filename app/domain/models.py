"""Pydantic models for API requests and responses."""
from __future__ import annotations

from typing import Any
from pydantic import BaseModel, Field


# ── Audio ────────────────────────────────────────

class TranscriptionResponse(BaseModel):
    transcript: str = Field(..., description="The transcribed text from the audio.")
    detected_language: str = Field(..., description="Language code detected by Whisper (e.g., 'ar', 'en').")


# ── Dataset ──────────────────────────────────────

class ColumnSchema(BaseModel):
    name: str
    type: str

class DatasetUploadResponse(BaseModel):
    filename: str
    table_name: str
    row_count: int
    columns: list[ColumnSchema] = Field(..., description="The schema of the dataset for the LLM.")


# ── Query / Analysis ─────────────────────────────

class AnalyzeRequest(BaseModel):
    dataset_name: str = Field(..., description="The table name returned from the dataset upload.")
    user_text: str = Field(..., description="The transcribed text from the voice command.")

class AnalyzeResponse(BaseModel):
    user_text: str
    generated_sql: str = Field(..., description="The SQLite query generated by the LLM.")
    result_data: list[dict[str, Any]] = Field(..., description="The data returned from the SQLite query.")
    explanation: str = Field(..., description="A natural language explanation of the results.")